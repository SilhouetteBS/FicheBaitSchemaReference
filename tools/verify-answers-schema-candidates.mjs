import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { objectNamesMatch } from '../src/data/objectNameMatching.js';

const input = JSON.parse(fs.readFileSync('data/research/answers-candidates.json', 'utf8'));
const products = JSON.parse(fs.readFileSync('data/products.json', 'utf8')).products;
const generated = Object.fromEntries(products.map((product) => [product.productKey, []]));
const rows = [];
for (const product of products) {
  const manifest = JSON.parse(fs.readFileSync(`data/${product.productKey}/versions.json`, 'utf8'));
  const versions = manifest.versions.map((entry) => {
    const schema = JSON.parse(fs.readFileSync(`data/${product.productKey}/${entry.version}/schema.json`, 'utf8'));
    const names = new Set(['tables', 'views', 'routines', 'triggers'].flatMap((type) =>
      (schema[type] ?? []).map((object) => (object.key ?? `${object.schemaName}.${object.name}`).toLowerCase())));
    return { version: entry.version, names };
  });
  for (const candidate of input.filter((item) => item.product === product.productKey)) {
    const confirmedVersions = versions.filter((item) => candidate.referencedObjects.length > 0
      && candidate.referencedObjects.every((reference) => objectNamesMatch(reference, item.names))).map((item) => item.version);
    rows.push({ product: product.productKey, title: candidate.title, url: candidate.url, confirmedVersions });
    // Matching names alone must not publish raw private research material.
    if (!candidate.publishedCandidate || confirmedVersions.length === 0) continue;
    generated[product.productKey].push({
      ...candidate.publishedCandidate,
      summary: candidate.publishedCandidate.summary.replace('Schema-verified', 'Object-name-matched'),
      tags: candidate.publishedCandidate.tags.map((tag) => tag === 'Schema matched' ? 'Object names matched' : tag),
      confirmedVersions,
    });
  }
}
const moduleText = '// Generated by tools/verify-answers-schema-candidates.mjs.\n'
  + '// Do not edit this file manually; rerun the verification tool instead.\n\n'
  + `export const generatedReportingCandidates = ${JSON.stringify(generated, null, 2)};\n`;
const report = ['# Answers Object-Name Verification', '',
  'Generated from sanitized tracked inputs. Matching does not validate columns, SQL syntax, semantics, permissions, or execution.', '',
  '| Product | Source | Versions With All Object Names Matched |', '| --- | --- | --- |',
  ...rows.map((row) => `| ${row.product} | [${row.title.replaceAll('|', '\\|')}](${row.url}) | ${row.confirmedVersions.join(', ') || 'Not established'} |`), '',
].join('\n');
const outputs = new Map([
  ['src/data/generatedReportingCandidates.js', moduleText],
  ['docs/answers-sql-object-name-verification.md', report],
]);
for (const [file, content] of outputs) {
  if (process.argv.includes('--check')) assert.equal(fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n'), content, `${file} is stale. Run npm run verify:answers-schema.`);
  else fs.writeFileSync(path.resolve(file), content);
}
console.log(`Verified ${rows.length} sanitized research inputs; ${Object.values(generated).flat().length} published candidates have matching object names.`);
