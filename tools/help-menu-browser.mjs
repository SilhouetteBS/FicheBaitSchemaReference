import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';

const base = process.env.APP_URL ?? 'http://127.0.0.1:4177';
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/?product=forms&version=12.0.2607.40144&view=tables&table=dbo.cf_bp_main_instances`, { waitUntil: 'networkidle' });
  assert.equal(await page.locator('.community-disclaimer summary').innerText(), 'Independent database schema reference. Read-only use; validate changes in a test environment.');
  assert.match(await page.locator('.community-disclaimer').textContent(), /not affiliated with or endorsed by\s+Laserfiche/);
  const search = page.getByLabel('Search tables, columns, descriptions');
  await search.fill('cf_bp_main_instances');
  const selection = await page.locator('.table-detail h2').innerText();
  const help = page.getByRole('button', { name: 'Help', exact: true });
  const menu = page.getByRole('menu', { name: 'Help', exact: true });
  const guide = menu.getByRole('menuitem', { name: 'User Guide', exact: true });
  const about = menu.getByRole('menuitem', { name: 'About', exact: true });
  const feature = menu.getByRole('menuitem', { name: 'Feature Requests (opens in a new tab)', exact: true });
  await help.focus();
  await page.keyboard.press('Enter');
  await guide.waitFor();
  assert.equal(await guide.evaluate(el => el === globalThis.document.activeElement), true);
  assert.deepEqual(await menu.getByRole('menuitem').allTextContents(), ['User Guide', 'About', 'Keyboard shortcuts', 'Feature Requests']);
  assert.equal(await feature.getAttribute('href'), 'https://fichebait.com/suggest-a-feature/?feature_product=FicheBait%20Schema%20Reference');
  assert.equal(await feature.getAttribute('target'), '_blank');
  assert.equal(await guide.getAttribute('target'), null);
  assert.equal(await help.evaluate(el => globalThis.getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)');
  await page.keyboard.press('End');
  assert.equal(await feature.evaluate(el => el === globalThis.document.activeElement), true);
  await page.keyboard.press('Home');
  assert.equal(await guide.evaluate(el => el === globalThis.document.activeElement), true);
  await page.keyboard.press('ArrowUp');
  assert.equal(await feature.evaluate(el => el === globalThis.document.activeElement), true);
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('ArrowDown');
  assert.equal(await about.evaluate(el => el === globalThis.document.activeElement), true);
  await page.keyboard.press('Escape');
  assert.equal(await menu.count(), 0);
  assert.equal(await help.evaluate(el => el === globalThis.document.activeElement), true);
  await page.keyboard.press('ArrowUp');
  assert.equal(await feature.evaluate(el => el === globalThis.document.activeElement), true);
  await page.keyboard.press('Tab');
  assert.equal(await menu.count(), 0);
  await help.click();
  await page.keyboard.press('End');
  await page.keyboard.press('Home');
  await page.keyboard.press('Tab');
  assert.equal(await about.evaluate(el => el === globalThis.document.activeElement), true);
  await page.keyboard.press('Shift+Tab');
  assert.equal(await guide.evaluate(el => el === globalThis.document.activeElement), true);
  await page.keyboard.press('Shift+Tab');
  assert.equal(await menu.count(), 0);
  await help.click();
  await page.getByRole('heading', { name: 'FicheBait Schema Reference', exact: true }).click();
  assert.equal(await menu.count(), 0);
  await help.click();
  const menuAudit = await new AxeBuilder({ page }).include('.help-menu').analyze();
  assert.deepEqual(menuAudit.violations, []);
  const bounds = await menu.boundingBox();
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 1440 && bounds.y >= 0);
  await page.screenshot({ path: 'outputs/help-menu.png' });
  await about.click();
  const dialog = page.getByRole('dialog', { name: 'About Schema Reference' });
  await dialog.waitFor();
  assert.equal(await search.inputValue(), 'cf_bp_main_instances');
  assert.equal(await page.locator('.table-detail h2').innerText(), selection);
  assert.match(await dialog.innerText(), /Not affiliated with or endorsed by Laserfiche/);
  assert.match(await dialog.innerText(), /independent database schema reference/);
  assert.deepEqual((await new AxeBuilder({ page }).include('[role="dialog"]').analyze()).violations, []);
  await page.keyboard.press('Escape');
  assert.equal(await dialog.count(), 0);
  assert.equal(await help.evaluate(el => el === globalThis.document.activeElement), true);
  await help.click();
  await about.click();
  await page.getByRole('button', { name: 'Close About', exact: true }).click();
  assert.equal(await help.evaluate(el => el === globalThis.document.activeElement), true);
  const returnQuery = new URL(page.url()).search;
  assert.equal(await page.locator('.topbar-actions [title="Keyboard shortcuts"]').count(), 0);
  await help.click();
  await menu.getByRole('menuitem', { name: 'Keyboard shortcuts', exact: true }).click();
  const shortcuts = page.getByRole('dialog', { name: 'Keyboard shortcuts', exact: true });
  await shortcuts.waitFor();
  assert.equal(await menu.count(), 0);
  await page.keyboard.press('Escape');
  assert.equal(await shortcuts.count(), 0);
  assert.equal(await help.evaluate(el => el === globalThis.document.activeElement), true);
  await page.keyboard.press('?');
  await shortcuts.waitFor();
  await page.getByRole('button', { name: 'Close keyboard shortcuts', exact: true }).click();
  assert.equal(await help.evaluate(el => el === globalThis.document.activeElement), true);
  assert.equal(await search.inputValue(), 'cf_bp_main_instances');
  assert.equal(await page.locator('.table-detail h2').innerText(), selection);
  const tagClasses = ['confidence confidence-unknown', 'confidence confidence-inferred', 'confidence confidence-observed', 'confidence confidence-confirmed',
    'community-tag-source', 'community-tag-matched', 'community-tag-neutral', 'community-tag-untested', 'community-tag-review', 'community-tag-readonly', 'community-tag-context'];
  const appColors = await page.evaluate(classes => {
    const container = globalThis.document.createElement('div');
    globalThis.document.body.append(container);
    const colors = classes.map(className => {
      container.className = className.startsWith('confidence ') ? '' : 'community-pattern-tags';
      const sample = globalThis.document.createElement('span');
      sample.className = className;
      container.append(sample);
      const style = globalThis.getComputedStyle(sample);
      return [style.color, style.backgroundColor];
    });
    container.remove();
    return colors;
  }, tagClasses);
  await help.click();
  await guide.click();
  await page.getByRole('heading', { name: 'How it works', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Tags and legends', exact: true }).waitFor();
  const returnLink = page.getByRole('link', { name: 'Open Schema Reference', exact: true }).first();
  assert.equal(new URL(await returnLink.getAttribute('href'), base).search, returnQuery);
  for (const [index, className] of tagClasses.entries()) {
    const colors = await page.locator(`#legends .${className.split(' ').join('.')}`).evaluate(el => {
      const style = globalThis.getComputedStyle(el);
      return [style.color, style.backgroundColor];
    });
    assert.deepEqual(colors, appColors[index], `Guide palette differs for ${className}`);
  }
  assert.deepEqual((await new AxeBuilder({ page }).analyze()).violations, []);
  await returnLink.click();
  await page.locator('.table-detail h2').waitFor();
  assert.equal(await page.locator('.table-detail h2').innerText(), selection);
  assert.equal(await search.inputValue(), 'cf_bp_main_instances');
  // Opening About must not clear a focused diagram via the global Escape shortcut.
  await page.goto(`${base}/?product=forms&version=12.0.2607.40144&view=diagram&diagramMode=focused&diagramFocus=dbo.cf_bp_main_instances`, { waitUntil: 'networkidle' });
  await help.waitFor();
  const beforeAbout = page.url();
  await help.click();
  await about.click();
  await page.keyboard.press('Escape');
  assert.equal(page.url(), beforeAbout);
  assert.deepEqual(errors, []);
  console.log('Help checks passed: destinations, menu keyboard/Tab/dismissal, focus restoration, preserved state, guide return, accessibility, and viewport bounds.');
} finally { await browser.close(); }
