import assert from 'node:assert/strict';
import fs from 'node:fs';
import { chromium } from 'playwright';

const base = process.env.APP_URL ?? 'http://127.0.0.1:4177';
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.addInitScript(() => {
    globalThis.localStorage.setItem('lfdd.favoriteObjects.v1', '{}');
    globalThis.localStorage.setItem('lfdd.diagramPresets.v1', '[null]');
    globalThis.localStorage.setItem('lfdd.localNotes', '[]');
  });
  const start = new URL(base);
  start.search = new URLSearchParams({ product: 'forms', version: '12.0.2607.40137', view: 'tables', table: 'dbo.__TransactionHistory' });
  await page.goto(start.toString(), { waitUntil: 'networkidle' });
  assert.match(await page.locator('.table-context-bar').innerText(), /Load history/);
  await page.getByRole('button', { name: /Stability Load history/ }).click();
  await page.waitForFunction(() => globalThis.document.querySelector('.table-context-bar')?.textContent.includes('5/5 versions'));
  assert.match(await page.locator('.table-context-bar').innerText(), /0 changed cols/);
  await page.getByLabel('Version', { exact: true }).selectOption('11.0.2311.50564');
  await page.waitForFunction(() => new URL(globalThis.location.href).searchParams.get('version') === '11.0.2311.50564');
  assert.equal(new URL(page.url()).searchParams.get('table'), 'dbo.__TransactionHistory');
  await page.evaluate(() => { globalThis.__navigationSentinel = 'same-document'; });
  await page.getByRole('button', { name: 'Reporting', exact: true }).click();
  await page.getByRole('heading', { name: 'Reporting guide', exact: true }).waitFor();
  await page.goBack();
  await page.locator('.table-context-bar').waitFor();
  assert.equal(await page.evaluate(() => globalThis.__navigationSentinel), 'same-document');
  await page.goForward();
  await page.getByRole('heading', { name: 'Reporting guide', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => globalThis.__navigationSentinel), 'same-document');

  const schema = JSON.parse(fs.readFileSync('data/forms/11.0.2311.50564/schema.json', 'utf8'));
  const routine = schema.routines[0].key;
  await page.getByRole('button', { name: 'Command', exact: true }).click();
  await page.getByLabel('Command search').fill(routine);
  await page.locator('.command-results button').filter({ hasText: routine }).first().click();
  await page.waitForFunction((key) => globalThis.document.querySelector('.object-detail-panel h3')?.textContent === key, routine);
  assert.equal(new URL(page.url()).searchParams.get('object'), routine);
  const correction = new URL(await page.getByRole('link', { name: 'Report a correction or update' }).getAttribute('href'));
  assert.equal(correction.searchParams.get('area'), 'Objects');
  assert.equal(correction.searchParams.get('schema_object'), routine);
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('.object-detail-panel h3').textContent(), routine);
  await page.getByRole('button', { name: 'Reporting', exact: true }).click();
  await page.getByLabel('Find scripts').fill('active task');
  const script = page.locator('.reporting-nav button').filter({ hasText: 'Forms active task and Monitor reporting' });
  await script.click();
  await page.getByRole('tab', { name: 'Review notes', exact: true }).click();
  await page.locator('.reporting-markdown h1').waitFor();
  assert.equal(await page.locator('.reporting-markdown script').count(), 0);
  await page.getByRole('tab', { name: 'Review notes', exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.getByRole('tab', { name: 'Links to Resources', exact: true }).getAttribute('aria-selected'), 'true');

  const denied = await browser.newPage();
  await denied.addInitScript(() => Object.defineProperty(globalThis, 'localStorage', { get() { throw new Error('Storage disabled'); } }));
  await denied.goto(start.toString(), { waitUntil: 'networkidle' });
  await denied.getByRole('heading', { name: 'FicheBait Schema Reference', exact: true }).waitFor();
  assert.ok(await denied.locator('.table-context-bar').isVisible());
  const retryPage = await browser.newPage();
  const oldSchema = '**/data/forms/11.0.2311.50564/schema.json';
  await retryPage.route(oldSchema, (route) => route.abort());
  await retryPage.goto(start.toString(), { waitUntil: 'networkidle' });
  await retryPage.getByRole('button', { name: /Stability Load history/ }).click();
  await retryPage.getByRole('alert').filter({ hasText: 'Some version metadata could not be loaded' }).waitFor();
  assert.match(await retryPage.locator('.table-context-bar').innerText(), /Load history/);
  await retryPage.unroute(oldSchema);
  await retryPage.getByRole('button', { name: /Stability Load history/ }).click();
  await retryPage.getByRole('button', { name: /Stability Load history/ }).click();
  await retryPage.waitForFunction(() => globalThis.document.querySelector('.table-context-bar')?.textContent.includes('5/5 versions'));
  const racePage = await browser.newPage();
  await racePage.goto(start.toString(), { waitUntil: 'networkidle' });
  await racePage.route(oldSchema, async (route) => {
    await new Promise((resolve) => setTimeout(resolve, 600));
    await route.continue();
  });
  await racePage.getByLabel('Version', { exact: true }).selectOption('11.0.2311.50564');
  await racePage.getByLabel('Product', { exact: true }).selectOption('lfds');
  await racePage.waitForFunction(() => globalThis.document.querySelector('[aria-label="Product"]')?.value === 'lfds');
  await racePage.waitForTimeout(750);
  assert.equal(new URL(racePage.url()).searchParams.get('product'), 'lfds');
  assert.equal(await racePage.getByLabel('Version', { exact: true }).inputValue(), '12.0.2607.421');
  assert.deepEqual(errors, []);
  console.log('Browser review regressions passed: history, persistence, object navigation, corrections, script search, Markdown, tabs, and unavailable storage.');
} finally { await browser.close(); }
